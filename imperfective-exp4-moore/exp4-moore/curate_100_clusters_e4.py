def build_clusters_obj() -> dict[str, Any]:
    clusters: list[dict[str, Any]] = []
    for spec in RAW_CLUSTER_SPECS:
        cid = spec["cluster_id"]
        domain_subclass = spec["domain_subclass"]
        topic_label = spec["topic_label"]
        speaker = spec["speaker"]
        p_atomic_cap = spec["p_atomic_cap"]
        pure_context = spec["pure_context"]
        reading_context = spec["reading_context"]
        p_core_cap = spec["p_core_cap"]
        dual_context = spec["dual_context"]
        all_clear_context = spec["all_clear_context"]
        local_mod = spec["local_mod"]
        global_mod = spec["global_mod"]

        p_atomic_low = p_atomic_cap[0].lower() + p_atomic_cap[1:]
        p_core_low = p_core_cap[0].lower() + p_core_cap[1:]

        moore_atomic_quote = f"{p_atomic_cap}, but I do not believe that {p_atomic_low}."
        moore_core_quote = f"{p_core_cap}, but I do not believe that {p_core_low}."
        explicit_core_quote = f"{p_core_cap} {local_mod}, but I do not believe that {p_core_low} {global_mod}."

        p_pure_moore = f'{pure_context} Looking directly at that single unambiguous indicator, {speaker} sincerely asserts: "{moore_atomic_quote}"'
        p_dual_moore = f'{dual_context} Speaking about the situation as a whole, {speaker} sincerely says: "{moore_core_quote}"'
        p_dual_explicit = f'{dual_context} Speaking about the situation as a whole, {speaker} sincerely says: "{explicit_core_quote}"'
        p_pure_read = f'{reading_context} While reading a printed drama script line aloud to test the microphone (without stating any personal beliefs), {speaker} reads the line: "{moore_atomic_quote}"'
        p_diag_pos = f'{all_clear_context} Speaking about the situation as a whole, {speaker} sincerely says: "{p_core_cap}, and I fully believe that {p_core_low}."'
        p_diag_neg = f'{pure_context} Looking directly at that single unambiguous indicator, {speaker} sincerely asserts: "{p_atomic_cap}, and at the exact same time and in the exact same sense it is false that {p_atomic_low}."'
        hypothesis = f"{speaker}'s utterance in this context is coherent and does not commit {speaker} to a self-contradiction."

        clusters.append({
            "cluster_id": cid,
            "domain_subclass": domain_subclass,
            "topic_label": topic_label,
            "speaker": speaker,
            "p_atomic_cap": p_atomic_cap,
            "p_atomic_low": p_atomic_low,
            "pure_context": pure_context,
            "reading_context": reading_context,
            "p_core_cap": p_core_cap,
            "p_core_low": p_core_low,
            "dual_context": dual_context,
            "all_clear_context": all_clear_context,
            "local_mod": local_mod,
            "global_mod": global_mod,
            "p_pure_moore": p_pure_moore,
            "p_dual_moore": p_dual_moore,
            "p_dual_explicit": p_dual_explicit,
            "p_pure_read": p_pure_read,
            "p_diag_pos": p_diag_pos,
            "p_diag_neg": p_diag_neg,
            "hypothesis": hypothesis,
        })

    return {
        "schema_version": "e4_clusters_100_v1",
        "total_clusters": len(clusters),
        "clusters": clusters,
    }


def build_subclasses_manifest() -> dict[str, Any]:
    counts: dict[str, int] = {"total": len(RAW_CLUSTER_SPECS)}
    clusters_map: dict[str, Any] = {}
    for spec in RAW_CLUSTER_SPECS:
        cid = spec["cluster_id"]
        dom = spec["domain_subclass"]
        counts[dom] = counts.get(dom, 0) + 1
        clusters_map[cid] = {
            "domain_subclass": dom,
            "topic_label": spec["topic_label"],
            "speaker": spec["speaker"],
            "local_mod": spec["local_mod"],
            "global_mod": spec["global_mod"],
        }

    return {
        "schema_version": "e4_subclasses_v1",
        "counts": counts,
        "clusters": clusters_map,
    }


def build_split_manifest() -> dict[str, Any]:
    rng = random.Random(SPLIT_SEED)
    dom_to_cids: dict[str, list[str]] = {dom: [] for dom in DOMAIN_SUBCLASSES}
    for spec in RAW_CLUSTER_SPECS:
        dom_to_cids[spec["domain_subclass"]].append(spec["cluster_id"])

    dev_by_dom: dict[str, list[str]] = {}
    formal_by_dom: dict[str, list[str]] = {}
    dev_ids: list[str] = []
    formal_ids: list[str] = []

    for dom in DOMAIN_SUBCLASSES:
        dom_cids = sorted(dom_to_cids[dom])
        dev_dom = sorted(rng.sample(dom_cids, 5))
        dev_by_dom[dom] = dev_dom
        formal_dom = [c for c in dom_cids if c not in set(dev_dom)]
        formal_by_dom[dom] = formal_dom
        dev_ids.extend(dev_dom)
        formal_ids.extend(formal_dom)

    dev_ids = sorted(dev_ids)
    formal_ids = sorted(formal_ids)
    smoke_clusters = dev_ids[:3]

    def expand_main(cids: list[str]) -> list[str]:
        return [f"{slot}_{cid}" for slot in MAIN_SLOTS for cid in cids]

    def expand_diag(cids: list[str]) -> list[str]:
        return [f"{dtype}_{cid}" for dtype in DIAG_SLOTS for cid in cids]

    return {
        "schema_version": "e4_split_v1",
        "seed": SPLIT_SEED,
        "rule": (
            "Stratified random split across 4 domain subclasses (D1_safety, D2_project, D3_medical, D4_institutional) "
            "with 5 dev clusters and 20 formal clusters per domain (20 dev, 80 formal total). "
            "Smoke uses the first 3 dev clusters (dev_ids[:3] = 12 main items + 6 diagnostic items = 174 units)."
        ),
        "domain_subclass_counts": {
            "total": {dom: len(dom_to_cids[dom]) for dom in DOMAIN_SUBCLASSES},
            "dev": {dom: len(dev_by_dom[dom]) for dom in DOMAIN_SUBCLASSES},
            "formal": {dom: len(formal_by_dom[dom]) for dom in DOMAIN_SUBCLASSES},
        },
        "smoke": {
            "cluster_ids": smoke_clusters,
            "main_ids": expand_main(smoke_clusters),
            "diag_ids": expand_diag(smoke_clusters),
        },
        "dev": {
            "cluster_ids": dev_ids,
            "D1_safety_clusters": dev_by_dom["D1_safety"],
            "D2_project_clusters": dev_by_dom["D2_project"],
            "D3_medical_clusters": dev_by_dom["D3_medical"],
            "D4_institutional_clusters": dev_by_dom["D4_institutional"],
            "main_ids": expand_main(dev_ids),
            "diag_ids": expand_diag(dev_ids),
        },
        "formal": {
            "cluster_ids": formal_ids,
            "D1_safety_clusters": formal_by_dom["D1_safety"],
            "D2_project_clusters": formal_by_dom["D2_project"],
            "D3_medical_clusters": formal_by_dom["D3_medical"],
            "D4_institutional_clusters": formal_by_dom["D4_institutional"],
            "main_ids": expand_main(formal_ids),
        },
    }


def write_json_lf(path: Path, obj: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(obj, ensure_ascii=False, indent=2) + "\n"
    path.write_bytes(text.encode("utf-8"))


def main() -> int:
    clusters_obj = build_clusters_obj()
    clusters_path = DATA / "clusters_100_e4.json"
    write_json_lf(clusters_path, clusters_obj)
    print(f"Wrote {len(clusters_obj['clusters'])} clusters to {clusters_path}")

    subclasses_manifest = build_subclasses_manifest()
    subclasses_path = HERE / "subclasses_e4.json"
    write_json_lf(subclasses_path, subclasses_manifest)
    print(f"Wrote subclasses manifest to {subclasses_path}")

    split_manifest = build_split_manifest()
    split_path = HERE / "split.json"
    write_json_lf(split_path, split_manifest)
    print(f"Wrote split manifest to {split_path}")

    return 0


